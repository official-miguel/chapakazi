export type Lang = keyof typeof words
export type WordKey = keyof (typeof words)['en']

const STORAGE_KEY = 'ck.lang'

function readSavedLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'sw') return saved
  } catch {
    // Storage can be blocked (private mode); fall through to the default.
  }
  return 'en'
}

type I18n = {
  lang: Lang
  setLang: (lang: Lang) => void
  /** Looks up a phrase. `fill` replaces {placeholders}, e.g. t('lock.tooMany', { s: 30 }). */
  t: (key: WordKey, fill?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readSavedLang)

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const setLang = useCallback((next: Lang) => {
    setLangState(next)
    try {
      localStorage.setItem(STORAGE_KEY, next)
    } catch {
      // Not saved; the choice still applies until the app is closed.
    }
  }, [])

  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang,
      t: (key, fill) => {
        const phrase: string = words[lang][key]
        if (!fill) return phrase
        return phrase.replace(/\{(\w+)\}/g, (whole, name: string) => (name in fill ? String(fill[name]) : whole))
      },
    }),
    [lang, setLang],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
